import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { delimiter, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { solveLock, createSolverConfig } from 'gothic-lock-solver';
import * as GothicLockSolver from 'gothic-lock-solver';

const config = createSolverConfig({ maxDenseBytes: 0 });
assert.ok(Object.isFrozen(config));
assert.deepEqual(solveLock([6, 2], [[0, -1], [0, 0]], config), [[0, -2]]);
assert.deepEqual(GothicLockSolver.solveLock([4, 4], [[0, 0], [0, 0]]), []);
assert.deepEqual(Object.keys(GothicLockSolver).sort(), ['LockInputError', 'SearchLimitError', 'createSolverConfig', 'solveLock']);
assert.ok(import.meta.resolve('gothic-lock-solver').includes('/node_modules/gothic-lock-solver/dist/'));
const manifest: unknown = JSON.parse(readFileSync(new URL('./node_modules/gothic-lock-solver/package.json', import.meta.url), 'utf8'));
assert.ok(typeof manifest === 'object' && manifest !== null);
for (const field of ['dependencies', 'optionalDependencies', 'peerDependencies']) assert.deepEqual(Reflect.get(manifest, field) ?? {}, {});
assert.deepEqual(Reflect.get(manifest, 'bundleDependencies') ?? [], []);
assert.equal(Reflect.get(manifest, 'private'), false);
const scripts: unknown = Reflect.get(manifest, 'scripts');
assert.ok(typeof scripts === 'object' && scripts !== null);
for (const lifecycle of ['preinstall', 'install', 'postinstall', 'prepare']) assert.equal(Reflect.get(scripts, lifecycle), undefined);
assert.deepEqual(Reflect.get(manifest, 'bin'), { 'gothic-lock-solver': './dist/gothic-lock-solver.cli.mjs' });
for (const path of ['gothic-lock-solver/dist/gothic-lock-solver.mjs', 'gothic-lock-solver/dist/gothic-lock-solver.min.mjs']) {
  const api: unknown = await import(path);
  assert.ok(typeof api === 'object' && api !== null);
  assert.deepEqual(Object.keys(api).sort(), Object.keys(GothicLockSolver).sort());
  const factory: unknown = Reflect.get(api, 'createSolverConfig');
  const solve: unknown = Reflect.get(api, 'solveLock');
  assert.equal(typeof factory, 'function');
  assert.equal(typeof solve, 'function');
  if (typeof factory !== 'function' || typeof solve !== 'function') throw new Error('Malformed ESM exports');
  const settings: unknown = Reflect.apply(factory, undefined, [{ maxDenseBytes: 0 }]);
  assert.deepEqual(settings, config);
  assert.deepEqual(Reflect.apply(solve, undefined, [[6, 2], [[0, -1], [0, 0]], settings]), [[0, -2]]);
}
console.log(JSON.stringify({ node: process.version, installed: true, namespace: Object.keys(GothicLockSolver).sort() }));

const input = new URL('./lock.json', import.meta.url);
const configFile = new URL('./config.json', import.meta.url);
const output = new URL('./solution.json', import.meta.url);
const executable = new URL('./node_modules/gothic-lock-solver/dist/gothic-lock-solver.cli.mjs', import.meta.url);
const bin = fileURLToPath(new URL('./node_modules/.bin/gothic-lock-solver', import.meta.url));
assert.ok(existsSync(bin));
writeFileSync(input, JSON.stringify({ state: [6, 2], links: [[0, -1], [0, 0]] }));
writeFileSync(configFile, JSON.stringify({ maxDenseBytes: 0 }));
let cli = spawnSync(bin, [fileURLToPath(input), '--config', fileURLToPath(configFile), '--output', fileURLToPath(output)], { encoding: 'utf8', env: { ...process.env, PATH: `${dirname(process.execPath)}${delimiter}${process.env['PATH'] ?? ''}` } });
assert.equal(cli.status, 0);
assert.equal(cli.stderr, '');
const solution: unknown = JSON.parse(readFileSync(output, 'utf8'));
assert.ok(typeof solution === 'object' && solution !== null);
assert.deepEqual(Reflect.get(solution, 'commands'), [{ plate: 1, direction: 'right', steps: 2 }]);
writeFileSync(input, JSON.stringify({ state: [1, 7], links: [[0, 1], [1, 0]] }));
cli = spawnSync(process.execPath, [fileURLToPath(executable), fileURLToPath(input)], { encoding: 'utf8' });
assert.equal(cli.status, 2);
writeFileSync(configFile, JSON.stringify({ unknown: 1 }));
cli = spawnSync(process.execPath, [fileURLToPath(executable), fileURLToPath(input), '--config', fileURLToPath(configFile)], { encoding: 'utf8' });
assert.equal(cli.status, 1);
writeFileSync(input, '{');
cli = spawnSync(process.execPath, [fileURLToPath(executable), fileURLToPath(input)], { encoding: 'utf8' });
assert.equal(cli.status, 1);
console.log(JSON.stringify({ installedCli: true, node: process.version, exitCodes: [0, 1, 2] }));
